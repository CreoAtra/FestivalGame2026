/* ============================================================
  判定に使うデータについて
  ============================================================

  ■ fruits について

  fruits は「今、画面に落ちているフルーツ」が入った配列です。
  フルーツが出てくるたびに増え、取られるか画面外に落ちると減ります。
  中身は下のような形のオブジェクトで、常にこの形です。

    {
      type:   "apple",  // 種類。下の一覧のどれかです
      x:      100,      // 左上の角のX座標
      y:      0,        // 左上の角のY座標。増えるほど下に落ちます
      width:  40,
      height: 40,
      speed:  3         // 1フレームあたり何px落ちるか。判定では使いません
    }

  type に入る文字列は次の6つです。

    "apple"  "banana"  "grape"   … 通常フルーツ
    "bonus"                      … 高得点フルーツ
    "damage"                     … ダメージフルーツ
    "clock"                      … 時計

  種類ごとに判定を変える必要はありません。
  ダメージフルーツも「キャッチした」ものとして同じように扱ってください。
  スコアを足すのかライフを減らすのかは、ゲームロジック担当が type を見て決めます。


  ■ 座標の見かた

  画面の左上の角が (0, 0) です。
  X座標は右に行くほど大きくなり、画面の右端が 400 です。
  Y座標は下に行くほど大きくなり、画面の一番下が 700 です。

    (0, 0) ──────────────→ X  (400, 0)
      │
      │        画面
      │
      ↓
      Y
    (0, 700)              (400, 700)


  ■ player.x / player.y と、フルーツの x / y はどこを指すか

  どちらも、その四角形の「左上の角」の座標です。中心ではありません。
  なので、ある物が画面上で占める範囲は次のようになります。

    左端 = x
    右端 = x + width
    上端 = y
    下端 = y + height

  Y座標は下に行くほど大きくなります。画面の一番上が 0 で、
  一番下が 700 です。フルーツが y: 0 で現れて y が増えていくのは、
  上から下に落ちているからです。
  X座標は一番左が0です。


  ■ 呼ばれるタイミング

  main.js の draw() から、毎フレーム1回呼ばれます。
  呼ばれる時点で、player と fruits はどちらもこのフレームの位置に
  更新し終わっています。順番は次の通りです。

    updatePlayer()  → キャラを動かす
    updateFruits()  → フルーツを落とす
    checkCollisions()  ← ここ
    applyCaughtFruits()  → スコアやライフに反映する


  ■ fruits から取り除く、とは

  取ったフルーツを配列に残したままにすると、次のフレームでも
  重なったままなので、1個のフルーツで何度もスコアが入ってしまいます。
  そうならないように、取ったものは fruits から消してください。

  また、画面の下まで落ちて取り逃したフルーツを消すのもフルーツ生成担当です。
  ここで消すのは「キャッチしたもの」だけで大丈夫です。


  ■ 返す値

  キャッチしたフルーツのオブジェクトそのものを、配列に入れて返してください。
  ゲームロジック担当がその中の type を見て処理を振り分けます。

    戻り値の例: [ { type: "apple", ... }, { type: "clock", ... } ]
    何も取っていないフレーム: []

  フルーツが重なって落ちてくると、1フレームで2個以上同時に取れることが
  あります。そのため、1個だけ返すのではなく配列にしてあります。

  ============================================================ */


